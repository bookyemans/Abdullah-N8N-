import assert from 'node:assert/strict';
import { onRequestGet as conversions } from '../functions/api/admin/conversions.js';

const env = {
  SUPABASE_URL: 'https://project-ref.supabase.co',
  SUPABASE_ANON_KEY: 'anon-test',
  SUPABASE_SERVICE_ROLE_KEY: 'service-test'
};
const requests = [];
let authenticated = true;

globalThis.fetch = async (input, init = {}) => {
  const url = new URL(String(input));
  requests.push({ url, init });
  if (url.pathname === '/auth/v1/user') {
    return authenticated ? Response.json({ id: 'owner-uuid', email: 'owner@example.com' }) : Response.json({ message: 'invalid token' }, { status: 401 });
  }
  if (url.pathname.endsWith('/admin_profiles')) return Response.json([{ user_id: 'owner-uuid', role: 'owner', is_active: true }]);
  if (url.pathname.endsWith('/rpc/admin_conversion_summary')) {
    return Response.json({
      range_days: 30,
      totals: { unique_visitors: 100, page_views: 240, sessions: 130, total_leads: 8, converted_visitors: 7, conversion_rate: 7, lead_rate: 8, open_leads: 3, replied_leads: 2, closed_leads: 3, spam_leads: 1, whatsapp_clicks: 14 },
      daily: [], sources: [], services: [], statuses: { new: 2 }, top_pages: []
    });
  }
  return Response.json({ message: 'not found' }, { status: 404 });
};

const origin = 'https://site.example';
let response = await conversions({ request: new Request(`${origin}/api/admin/conversions?days=30`, { headers: { Authorization: 'Bearer valid-token' } }), env });
assert.equal(response.status, 200);
let data = await response.json();
assert.equal(data.totals.unique_visitors, 100);
assert.equal(data.totals.total_leads, 8);
assert.equal(data.totals.conversion_rate, 7);
let rpc = requests.find(x => x.url.pathname.endsWith('/rpc/admin_conversion_summary'));
assert.ok(rpc, 'conversion data must be generated by bounded PostgreSQL RPC');
assert.equal(rpc.init.method, 'POST');
assert.equal(rpc.init.headers.get('apikey'), 'anon-test');
assert.equal(rpc.init.headers.get('authorization'), 'Bearer valid-token');

response = await conversions({ request: new Request(`${origin}/api/admin/conversions?days=999`, { headers: { Authorization: 'Bearer valid-token' } }), env });
assert.equal(response.status, 200);
rpc = requests.filter(x => x.url.pathname.endsWith('/rpc/admin_conversion_summary')).at(-1);
assert.equal(JSON.parse(rpc.init.body).p_days, 90, 'range must be capped at 90 days');

authenticated = false;
response = await conversions({ request: new Request(`${origin}/api/admin/conversions`, { headers: { Authorization: 'Bearer invalid-token' } }), env: { ...env } });
assert.equal(response.status, 401, 'invalid sessions must not access conversion analytics');
console.log('Supabase conversion analytics tests passed: authenticated RPC, conversion metrics, bounded date range and invalid-session rejection.');
